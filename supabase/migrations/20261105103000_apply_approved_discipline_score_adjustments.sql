-- Approved discipline/praise score proposals become durable, auditable grade adjustments.
create table if not exists public.student_grade_adjustments (
  id bigint generated by default as identity primary key,
  tenant_school_id uuid not null references public.schools(id) on delete cascade,
  proposal_id bigint not null unique references public.discipline_score_proposals(id) on delete restrict,
  student_id integer not null references public.students(id) on delete cascade,
  target_score text not null check (target_score in ('continuous','discipline')),
  subject text not null default '',
  term text not null default '',
  delta numeric(5,2) not null,
  actor_role text not null check (actor_role in ('teacher','deputy')),
  source_record_ids bigint[] not null default '{}',
  applied_at timestamptz not null default now(),
  applied_by text not null default ''
);
create index if not exists student_grade_adjustments_student_idx
 on public.student_grade_adjustments(tenant_school_id,student_id,target_score,subject,term);
alter table public.student_grade_adjustments enable row level security;
-- This ledger is read through authenticated Edge Functions only. Those functions
-- apply the parent/student/manager and school-tenant filters before returning rows.
revoke all on public.student_grade_adjustments from anon, authenticated;
drop policy if exists student_grade_adjustments_school_read on public.student_grade_adjustments;
grant all on public.student_grade_adjustments to service_role;

create or replace function public.approve_discipline_score_proposal(
 p_proposal_id bigint,
 p_school_id uuid,
 p_reviewer text
) returns jsonb
language plpgsql
security definer
set search_path=public,pg_temp
as $$
declare
 v_proposal public.discipline_score_proposals%rowtype;
 v_adjustment public.student_grade_adjustments%rowtype;
begin
 select * into v_proposal
 from public.discipline_score_proposals
 where id=p_proposal_id and tenant_school_id=p_school_id
 for update;
 if not found then
   raise exception 'پیشنهاد امتیاز پیدا نشد.';
 end if;
 if v_proposal.status <> 'pending' then
   raise exception 'این پیشنهاد قبلاً بررسی شده است.';
 end if;
 insert into public.student_grade_adjustments(
   tenant_school_id,proposal_id,student_id,target_score,subject,delta,actor_role,source_record_ids,applied_by
 ) values (
   v_proposal.tenant_school_id,v_proposal.id,v_proposal.student_id,v_proposal.target_score,
   v_proposal.subject,v_proposal.proposed_delta,v_proposal.actor_role,v_proposal.source_record_ids,p_reviewer
 ) returning * into v_adjustment;
 update public.discipline_score_proposals
 set status='approved',reviewed_at=now(),reviewed_by=p_reviewer,
     review_note=case when coalesce(review_note,'')='' then 'امتیاز در دفتر تعدیلات نمره اعمال شد.' else review_note end
 where id=v_proposal.id and tenant_school_id=p_school_id;
 return jsonb_build_object('ok',true,'proposal_id',v_proposal.id,'adjustment_id',v_adjustment.id,
   'student_id',v_proposal.student_id,'target_score',v_proposal.target_score,'delta',v_proposal.proposed_delta);
end;
$$;
revoke all on function public.approve_discipline_score_proposal(bigint,uuid,text) from public,anon,authenticated;
grant execute on function public.approve_discipline_score_proposal(bigint,uuid,text) to service_role;
