-- Operational praise/discipline classification and reviewable score proposals.
alter table public.discipline_records
  add column if not exists record_type text not null default 'discipline',
  add column if not exists class_name text not null default '',
  add column if not exists subject text not null default '',
  add column if not exists updated_at timestamptz not null default now();

alter table public.discipline_records
  drop constraint if exists discipline_records_record_type_check;
alter table public.discipline_records
  add constraint discipline_records_record_type_check
  check (record_type in ('discipline','praise'));

create index if not exists discipline_records_school_class_type_date_idx
  on public.discipline_records (tenant_school_id, class_name, record_type, incident_date);
create index if not exists discipline_records_school_teacher_subject_idx
  on public.discipline_records (tenant_school_id, teacher_id, subject, student_id, record_type);

create table if not exists public.discipline_score_proposals (
  id bigint generated by default as identity primary key,
  tenant_school_id uuid not null references public.schools(id) on delete cascade,
  student_id integer not null references public.students(id) on delete cascade,
  actor_role text not null check (actor_role in ('teacher','deputy')),
  teacher_id integer null references public.teachers(id) on delete set null,
  subject text not null default '',
  discipline_count integer not null default 0,
  praise_count integer not null default 0,
  proposed_delta numeric(5,2) not null default 0,
  target_score text not null check (target_score in ('continuous','discipline')),
  status text not null default 'pending' check (status in ('pending','approved','rejected')),
  source_record_ids bigint[] not null default '{}',
  created_at timestamptz not null default now(),
  reviewed_at timestamptz,
  reviewed_by text,
  review_note text not null default ''
);
alter table public.discipline_score_proposals enable row level security;
drop policy if exists discipline_score_proposals_tenant_select on public.discipline_score_proposals;
create policy discipline_score_proposals_tenant_select on public.discipline_score_proposals
for select to authenticated using (
 tenant_school_id = private.frahoosh_current_school_id()
 and private.frahoosh_school_access_active(tenant_school_id)
);
drop policy if exists discipline_score_proposals_management_write on public.discipline_score_proposals;
create policy discipline_score_proposals_management_write on public.discipline_score_proposals
for all to authenticated using (
 tenant_school_id = private.frahoosh_current_school_id()
 and private.frahoosh_school_access_active(tenant_school_id)
 and lower(coalesce(private.frahoosh_current_role(),'')) in
 ('manager','مدیر','مدیریت','educational','معاون آموزشی','executive','معاون اجرایی')
) with check (
 tenant_school_id = private.frahoosh_current_school_id()
 and private.frahoosh_school_access_active(tenant_school_id)
 and lower(coalesce(private.frahoosh_current_role(),'')) in
 ('manager','مدیر','مدیریت','educational','معاون آموزشی','executive','معاون اجرایی')
);
