create table if not exists public.parent_association_requests (
 id bigint generated by default as identity primary key,
 tenant_school_id uuid not null references public.schools(id) on delete cascade,
 parent_user_id uuid not null references auth.users(id) on delete cascade,
 parent_username text not null,
 parent_name text not null default '',
 parent_phone text not null default '',
 student_id integer not null references public.students(id) on delete cascade,
 student_name text not null default '',
 request_type text not null check (char_length(request_type) between 3 and 120),
 expertise text not null default '',
 message text not null check (char_length(message) between 5 and 3000),
 status text not null default 'pending' check (status in ('pending','approved','rejected')),
 manager_note text not null default '',
 reviewed_by uuid references auth.users(id) on delete set null,
 reviewed_at timestamptz,
 created_at timestamptz not null default now(),
 updated_at timestamptz not null default now()
);
create index if not exists parent_association_requests_school_created_idx on public.parent_association_requests (tenant_school_id, created_at desc);
create index if not exists parent_association_requests_parent_idx on public.parent_association_requests (tenant_school_id, parent_user_id, created_at desc);
create index if not exists parent_association_requests_student_idx on public.parent_association_requests (tenant_school_id, student_id);
alter table public.parent_association_requests enable row level security;
