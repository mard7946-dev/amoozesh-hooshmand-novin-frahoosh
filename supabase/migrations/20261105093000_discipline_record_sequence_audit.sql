-- Ensure records can be inserted without client-supplied identifiers and retain an audit trail.
create sequence if not exists public.discipline_records_id_seq;
select setval('public.discipline_records_id_seq', coalesce((select max(id) from public.discipline_records),0)+1, false);
alter table public.discipline_records alter column id set default nextval('public.discipline_records_id_seq');
alter sequence public.discipline_records_id_seq owned by public.discipline_records.id;

alter table public.discipline_records
  add column if not exists deleted_at timestamptz;

create table if not exists public.discipline_record_audit (
  id bigint generated by default as identity primary key,
  tenant_school_id uuid not null,
  record_id integer not null,
  action text not null check (action in ('insert','update','delete')),
  actor_username text not null default '',
  actor_role text not null default '',
  before_data jsonb,
  after_data jsonb,
  created_at timestamptz not null default now()
);
alter table public.discipline_record_audit enable row level security;
revoke all on public.discipline_record_audit from anon, authenticated;
grant all on public.discipline_record_audit to service_role;

create index if not exists discipline_records_active_school_class_idx
  on public.discipline_records (tenant_school_id,class_name,incident_date)
  where deleted_at is null;
create index if not exists discipline_proposals_source_idx
  on public.discipline_score_proposals using gin(source_record_ids);
