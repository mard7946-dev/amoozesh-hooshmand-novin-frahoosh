import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const page=readFileSync("report-cards.html","utf8");
const api=readFileSync("supabase/functions/report-cards/index.ts","utf8");
const migration=readFileSync("supabase/migrations/20261118130000_professional_school_report_cards.sql","utf8");
const portal=readFileSync("portal.html","utf8");
const logo=readFileSync("assets/school-logo-watermark.txt","utf8").trim();
const script=[...page.matchAll(/<script>([\s\S]*?)<\/script>/g)].at(-1)?.[1];
assert.ok(script,"Report card page script exists");
assert.doesNotThrow(()=>new Function(script),"Report card page JavaScript parses");
for(const subject of ["عربی","علوم","زبان","ریاضی","مطالعات","فارسی","انضباط"])assert.ok(page.includes(subject)&&api.includes(subject),subject+" is present in the form and API");
assert.match(api,/managerRoles/);
assert.match(api,/executiveRoles/);
assert.match(api,/school_memberships/);
assert.match(api,/is_active",true/);
assert.match(api,/eq\("school_id",schoolId\)/);
assert.match(api,/eq\("tenant_school_id",schoolId\)/);
assert.match(api,/score<0\|\|score>20/);
assert.match(migration,/enable row level security/i);
assert.match(migration,/revoke all on public\.school_report_cards from anon, authenticated/i);
assert.match(migration,/grant all on public\.school_report_cards to service_role/i);
assert.match(page,/filter\(x=>x\.subject!=="انضباط"\)/);
assert.match(page,/sorted\.indexOf\(Number\(value\)\)\+1/);
assert.match(page,/Number\(x\.score\)<13/);
assert.match(page,/i\+=4/);
assert.match(page,/print-sheet/);
assert.match(page,/id="executiveName"/);
assert.match(page,/id="managerName"/);
assert.match(page,/school-logo-watermark\.txt/);
assert.ok(logo.startsWith("/9j/")&&logo.endsWith("9k="),"Embedded school logo is a JPEG data payload");
assert.match(portal,/name==='کارنامه میان‌ترم'/);
assert.match(portal,/selectedRole\.id==='manager'\|\|selectedRole\.id==='deputy'/);
console.log("Professional report card feature checks passed.");
