import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const page = readFileSync("academic-analytics.html", "utf8");
const api = readFileSync("supabase/functions/academic-analytics/index.ts", "utf8");
const portal = readFileSync("portal.html", "utf8");
const script = [...page.matchAll(/<script>([\s\S]*?)<\/script>/g)].at(-1)?.[1];
assert.ok(script, "Analytics page script exists");
assert.doesNotThrow(() => new Function(script), "Analytics page JavaScript parses");
for (const field of ["students", "student_grades", "teacher_classes"]) assert.ok(api.includes(field), field + " is read by the API");
assert.match(api, /managerRoles/);
assert.match(api, /executiveRoles/);
assert.match(api, /school_memberships/);
assert.match(api, /is_active/);
assert.match(api, /tenant_school_id/);
assert.match(api, /manager_released/);
assert.match(api, /grades: analysisGrades/);
assert.match(api, /managerPendingGradesCount/);
const groupAverageSource = script.match(/function groupAverage\(rows,key\)\{[\s\S]*?\nfunction classAssignments/);
assert.ok(groupAverageSource, "groupAverage helper exists");
const groupAverage = new Function("average", "validScores", groupAverageSource[0].replace(/\nfunction classAssignments[\s\S]*$/, "") + "; return groupAverage;")(
  rows => rows.length ? rows.reduce((sum, row) => sum + Number(row.score), 0) / rows.length : null,
  rows => rows.filter(row => Number.isFinite(Number(row.score)))
);
assert.equal(groupAverage([{ subject: "ریاضی", score: 18 }, { subject: "ریاضی", score: 16 }], "subject")[0].value, 17);
assert.equal(groupAverage([{ subject: "علوم", score: 15 }], row => row.subject)[0].label, "علوم");
assert.match(page, /id="roster"/);
assert.match(page, /دارای نمره/);
assert.match(page, /بدون نمره/);
assert.match(page, /id="classChart"/);
assert.match(page, /id="distributionChart"/);
assert.match(page, /id="classesChart"/);
assert.match(page, /id="gradeChart"/);
assert.match(page, /id="chartGrade"/);
assert.match(page, /مقایسه کل کلاس با میانگین پایه/);
assert.match(page, /ابتدا پایه و سپس کلاس را انتخاب کنید/);
assert.match(page, /نمرات معتبر/);
assert.match(page, /id="subjectChart"/);
assert.match(page, /id="teacherChart"/);
assert.match(page, /teacherForSelected/);
assert.match(page, /تخصیص فعال/);
assert.match(page, /printScope/);
assert.match(page, /چاپ گزارش کامل/);
assert.match(page, /چاپ فهرست/);
assert.match(page, /بدون امکان ویرایش/);
assert.match(portal, /مرکز تحلیل آموزشی و عملکرد کلاس‌ها/);
assert.match(portal, /تولید نمودار آموزشی/);
assert.match(portal, /academic-analytics\.html/);
console.log("Academic analytics feature checks passed.");
